def budget_for(price: float) -> str:
    if price <= 15.5:
        return "15"
    if price <= 27:
        return "25"
    if price <= 52:
        return "50"
    if price <= 110:
        return "100"
    return None

def main():
    rows = []
    seen = set()
    skipped = []
    for rec in PRODUCTS + MORE:
        if len(rec) != 6:
            skipped.append(("bad-tuple", rec[0] if rec else "?"))
            continue
        asin, name, price, vibes, recipients, why = rec
        if not asin or not name or not why:
            skipped.append(("incomplete", asin))
            continue
        if not isinstance(asin, str) or not (
            (len(asin) == 10 and asin.isalnum())
        ):
            skipped.append(("bad-asin", asin))
            continue
        # filter the accidental placeholder
        if name.lower() == "placeholder" or price <= 0:
            skipped.append(("placeholder", asin))
            continue
        if asin in seen:
            skipped.append(("duplicate", asin))
            continue
        b = budget_for(float(price))
        if not b:
            skipped.append(("over-budget", asin))
            continue
        seen.add(asin)
        approx = int(round(float(price)))
        rows.append({
            "id": asin,
            "asin": asin,
            "name": name,
            "approxPrice": approx,
            "budget": b,
            "vibes": vibes,
            "recipients": recipients,
            "why": why,
            "image": f"https://images-na.ssl-images-amazon.com/images/P/{asin}.01._SCLZZZZZZZ_.jpg",
        })

    out = Path(__file__).resolve().parents[1] / "data" / "products.json"
    out.write_text(json.dumps(rows, indent=2, ensure_ascii=False) + "\n")
    print(f"Wrote {len(rows)} products to {out}")
    print("Skipped:", skipped)

    # coverage report
    budgets = ["15", "25", "50", "100"]
    vibes = ["gamer", "cozy", "foodie", "tech", "outdoors", "collector", "beauty"]
    recips = ["me", "friend", "partner", "kid", "parent", "coworker"]
    print("\nBy budget:", {b: sum(1 for p in rows if p["budget"]==b) for b in budgets})
    print("By vibe:", {v: sum(1 for p in rows if v in p["vibes"]) for v in vibes})
    print("By recipient:", {r: sum(1 for p in rows if r in p["recipients"]) for r in recips})
    print("\nBudget x vibe counts:")
    gaps = []
    for b in budgets:
        for v in vibes:
            n = sum(1 for p in rows if p["budget"]==b and v in p["vibes"])
            if n < 2:
                gaps.append((b, v, n))
            print(f"  ${b} / {v:10} {n}")
    print("\nThin cells (<2):", gaps)

if __name__ == "__main__":
    main()
